    It is text with the statistics of Portuguese, not Portuguese: the gate says `:structured` (more
    structure than every noise control, less than all real text), and that is what it should say.

    ## 3. Any-to-any: every route of the hub, on held-out inputs

    Colour pairs never seen in any fit, new variants (jitter, lighting, sensor
    noise), new phases and amplitudes, noise at 10 dB.

    | route | what it measures | check | value | control | threshold | ok |
    |---|---|---|---|---|---|---|
    #{Enum.map_join(r.any_to_any, "\n", fn rt -> Enum.map_join(rt.checks, "\n", fn c -> "| #{rt.route} | #{rt.measures} | #{c.name} | #{v(c.value)} | #{v(c.control)} | #{c.threshold} | #{ok(c.pass)} |" end) end)}

    ## 4. Model merging

    A Portuguese specialist (A) and an English one (B), planted bigrams; bits/character on
    held-out text of each domain (lower is better).
