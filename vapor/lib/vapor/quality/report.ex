    | method | pt | en | mean | ms | receipt |
    |---|---|---|---|---|---|
    #{Enum.map_join(r.merge.methods, "\n", fn m -> "| #{m.method} | #{f(m.pt)} | #{f(m.en)} | #{f(m.mean)} | #{m.ms} | #{ok(m.receipt_ok)} |" end)}

    #{Enum.map_join(r.merge.checks, "\n", fn c -> "- #{ok(c.pass)} #{c.name}" end)}

    TIES and DARE presuppose sparse task vectors (small differences from a fine-tune);
    the differences between log-probability tables of two domains are dense, and pruning
    distorts them — measured here, not presumed.

    #{merge_real(Map.get(r, :merge_real))}

    #{real(Map.get(r, :real))}

    ## 5. Substrates

    #{if r.substrates.programs == [], do: "No native worker in this run (oracle only).", else: Enum.map_join(r.substrates.programs, "\n", fn p -> "- #{ok(p.bit_identical)} #{p.program}: native = oracle bit for bit" end)}

