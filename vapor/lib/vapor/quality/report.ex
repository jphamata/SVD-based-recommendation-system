    **#{passed} of #{length(checks)} checks passed.** Each check compares an output
    with the known truth **and** with a control that a noise generator would reach — passing
    means "signal", and a failure gives the distance. Methodology: [docs/QUALITY.md](../QUALITY.md).

    ## 1. The noise gates, calibrated before judging

    Each gate is fitted to negative controls (noise, shuffled signal, repetition) and
    positive ones (held-out real signal) and **refuses to exist** if they overlap. The margin is the
    gap between the worst negative and the worst positive.

    | gate | score | worst negative | worst positive | margin | controls |
    |---|---|---|---|---|---|
    #{Enum.map_join(r.gates, "\n", fn {name, g} -> "| #{name} | #{dir(g.direction)} | #{f(g.t_noise)} | #{f(g.t_natural)} | #{f(g.margin)} | #{controls(g.controls)} |" end)}

    ## 2. Text: a planted model through the whole stack

    A bigram counted on the Portuguese prose of `docs/`, embedded **exactly** in the weights of a
    Llama decoder (`Vapor.Quality.Planted`), admitted by the airlock, compiled and run.

    | measure | value |
    |---|---|
    | max \\|logit − log P\\| against the analytic table | #{e(r.text.max_table_error)} |
    | bits/character of the model (held out) | #{f(r.text.bits_per_char)} |
    | bits/character of the table | #{f(r.text.table_bits)} |
    | unigram baseline | #{f(r.text.unigram_bits)} |
    | uniform baseline | #{f(r.text.uniform_bits)} |
